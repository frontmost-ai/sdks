// Writes typescript/src/generated.ts from the shared operation list. Run: node codegen/typescript.mjs
// The output is a pure function of spec/openapi.json, so CI can regenerate it and fail on any diff.

import { writeFileSync } from "node:fs";
import { camel, load, pascal } from "./ir.mjs";

const ir = load();

/** One JSON Schema to one TypeScript type. */
function ts(s, indent = "") {
  if (!s || Object.keys(s).length === 0) return "unknown";
  if (s.$ref) return s.$ref.split("/").at(-1);
  if (s.const !== undefined) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  if (s.anyOf || s.oneOf) return [...new Set((s.anyOf ?? s.oneOf).map((x) => ts(x, indent)))].join(" | ");
  if (Array.isArray(s.type)) return s.type.map((t) => ts({ ...s, type: t }, indent)).join(" | ");
  switch (s.type) {
    case "null": return "null";
    case "string": return "string";
    case "integer":
    case "number": return "number";
    case "boolean": return "boolean";
    case "array": return `Array<${ts(s.items, indent)}>`;
    case "object": {
      const props = Object.entries(s.properties ?? {});
      if (props.length === 0) return "Record<string, unknown>";
      const req = new Set(s.required ?? []);
      const inner = indent + "  ";
      const lines = props.map(([k, v]) => `${doc(v.description, inner)}${inner}${k}${req.has(k) ? "" : "?"}: ${ts(v, inner)};`);
      return `{\n${lines.join("\n")}\n${indent}}`;
    }
    default: return "unknown";
  }
}

const doc = (text, indent = "") => (text ? `${indent}/** ${text.replace(/\*\//g, "*\\/")} */\n` : "");

/** Query params minus `cursor`, which the Page class sends. */
function queryType(op) {
  const props = op.query.filter((p) => p.name !== "cursor" || !op.paginated);
  if (props.length === 0) return null;
  const lines = props.map((p) => `${doc(p.description ?? p.schema.description, "  ")}  ${p.name}${p.required ? "" : "?"}: ${ts(p.schema, "  ")};`);
  return `{\n${lines.join("\n")}\n}`;
}

const out = [];
out.push(`// Generated by codegen/typescript.mjs from spec/openapi.json (${ir.title} ${ir.apiVersion}). Do not edit.`);
out.push(`import { Core, type ClientOptions, type Page, type RequestOptions } from "./core.js";`, "");

for (const [name, schema] of Object.entries(ir.schemas)) {
  out.push(`${doc(schema.description)}export type ${name} = ${ts(schema)};`, "");
}

for (const op of ir.operations) {
  const base = pascal(`${op.resource}_${op.verb}`);
  const q = queryType(op);
  if (q) out.push(`export type ${base}Params = ${q};`, "");
  if (op.body) out.push(`export type ${base}Body = ${ts(op.body)};`, "");
}

for (const resource of ir.resources) {
  const ops = ir.operations.filter((o) => o.resource === resource);
  out.push(`export class ${pascal(resource)}Resource {`, `  constructor(private readonly core: Core) {}`, "");
  for (const op of ops) {
    const base = pascal(`${op.resource}_${op.verb}`);
    const args = op.pathParams.map((p) => `${camel(p.name)}: string`);
    if (op.body) args.push(`body: ${base}Body`);
    const q = queryType(op);
    // A route with a required query param, such as industries.search with q, takes params with no default.
    if (q) args.push(op.query.some((p) => p.required) ? `params: ${base}Params` : `params: ${base}Params = {}`);
    args.push(`options?: RequestOptions`);
    let path = op.path;
    for (const p of op.pathParams) path = path.replace(`{${p.wire}}`, `\${encodeURIComponent(${camel(p.name)})}`);
    const ret = op.status === 204 ? "void" : op.response ?? "unknown";
    const init = [q ? "query: params" : null, op.body ? "body" : null, "options"].filter(Boolean).join(", ");
    const call = (fn) => `this.core.${fn}(${JSON.stringify(op.httpMethod)}, \`${path}\`, { ${init} })`;
    out.push(`  /** ${op.summary} \`${op.httpMethod} ${op.path}\` */`);
    if (op.paginated) {
      out.push(`  ${op.verb}(${args.join(", ")}): Page<${op.item ?? "unknown"}${op.response ? `, ${op.response}` : ""}> {`);
      out.push(`    return this.core.list(\`${path}\`, params, options);`);
    } else {
      out.push(`  ${op.verb}(${args.join(", ")}): Promise<${[ret, op.accepted].filter(Boolean).join(" | ")}> {`);
      out.push(`    return ${call("request")};`);
    }
    out.push(`  }`, "");
    if (op.accepted) {
      // A 202 reply says the work is still running. The AndWait method follows it to the final reply.
      out.push(`  /** Like \`${op.verb}\`, but waits while the work runs, then returns the ${ret}. */`);
      out.push(`  ${camel(`${op.verb}_and_wait`)}(${args.join(", ")}): Promise<${ret}> {`);
      out.push(`    return ${call("wait")};`, `  }`, "");
    }
  }
  out.push(`}`, "");
}

out.push(`/** The Frontmost AI client. \`new Frontmost()\` reads FRONTMOST_API_KEY. */`);
out.push(`export class Frontmost extends Core {`);
for (const r of ir.resources) out.push(`  readonly ${camel(r)} = new ${pascal(r)}Resource(this);`);
out.push(`  constructor(options?: ClientOptions) {`, `    super(options);`, `  }`, `}`, "");

writeFileSync(new URL("../typescript/src/generated.ts", import.meta.url), out.join("\n"));
console.log(`typescript/src/generated.ts: ${ir.operations.length} operations, ${Object.keys(ir.schemas).length} types`);
